#!/usr/bin/env node
/**
 * The helper extension for GNOME 42-44 (Ubuntu 22.04, Debian 12), made from the
 * one for GNOME 45+: same code, the old way of loading it (imports.* instead of
 * ES modules, init() instead of a default export). Run after changing
 * gnome-extension/lydia-helper@berelels/extension.js; a test checks it is current.
 */
const fs = require('fs');
const path = require('path');

const UUID = 'lydia-helper@berelels';
const SRC = path.join(__dirname, '..', 'gnome-extension', UUID);
const OUT = path.join(__dirname, '..', 'gnome-extension', 'legacy', UUID);

function legacy(source) {
  const lines = source.split('\n');
  const imports = lines.filter((l) => /^import /.test(l));
  const gi = imports.map((l) => /^import (\w+) from 'gi:\/\/(\w+)';$/.exec(l)).filter(Boolean).map((m) => m[2]);
  if (!imports.some((l) => l.includes('ui/main.js'))) throw new Error('main.js import not found');
  let body = lines.filter((l) => !/^import /.test(l)).join('\n');
  const cls = /^export default class (\w+) extends Extension \{$/m.exec(body);
  if (!cls) throw new Error('extension class not found');
  body = body.replace(cls[0], `class ${cls[1]} {`);
  const head = [
    '// Generated by build/legacy-extension.js from ../../lydia-helper@berelels/extension.js: do not edit.',
    `const { ${gi.join(', ')} } = imports.gi;`,
    'const Main = imports.ui.main;',
  ].join('\n');
  return `${head}\n${body.trimEnd()}\n\n// GNOME 42-44 load extensions this way\nfunction init() {\n  return new ${cls[1]}();\n}\n`;
}

function build() {
  const meta = JSON.parse(fs.readFileSync(path.join(SRC, 'metadata.json'), 'utf8'));
  return {
    'extension.js': legacy(fs.readFileSync(path.join(SRC, 'extension.js'), 'utf8')),
    'metadata.json': JSON.stringify({ ...meta, 'shell-version': ['42', '43', '44'] }, null, 2) + '\n',
  };
}

if (require.main === module) {
  fs.mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(build())) fs.writeFileSync(path.join(OUT, name), text);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}

module.exports = { build, OUT };
