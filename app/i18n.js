  const LANGS = ['pt', 'en', 'es'];
  // Each language's own name, for the picker.
  const NAMES = { pt: 'Português (Brasil)', en: 'English', es: 'Español' };
  let current = 'pt';

  /** "system" + the system's locales (["pt-BR", "en-US"...]) -> pt | en | es. Unknown: English. */
  function resolve(pref, locales = []) {
    if (LANGS.includes(pref)) return pref;
    for (const l of locales) {
      const code = String(l).toLowerCase().slice(0, 2);
      if (LANGS.includes(code)) return code;
    }
    return 'en';
  }

  function setLang(lang) {
    current = LANGS.includes(lang) ? lang : 'en';
  }

  function t(key, vars) {
    let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  }

  /** 1 decimal, with the language's separator: 4,2 / 4.2 */
  const num = (x, digits = 1) => {
    const s = x.toFixed(digits);
    return current === 'en' ? s : s.replace('.', ',');
  };

  const api = { LANGS, NAMES, resolve, setLang, t, num, lang: () => current, htmlLang: () => ({ pt: 'pt-BR', en: 'en', es: 'es' })[current] };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.i18n = api;
